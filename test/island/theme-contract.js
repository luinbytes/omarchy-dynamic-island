const assert = require("node:assert/strict")
const fs = require("node:fs")
const path = require("node:path")

const base = path.resolve(__dirname, "../../shell/plugins/island")
const renderers = ["ActivityIcon.qml", "IslandContent.qml", "MediaContent.qml", "ActivityVisual.qml", "IslandSurface.qml"]
for (const name of renderers) {
  const source = fs.readFileSync(path.join(base, name), "utf8")
  assert.match(source, /import qs\.Commons/, `${name} reads direct system theme bindings`)
  assert.doesNotMatch(source, /Sans Serif|#[0-9a-f]{3,8}/i, `${name} has no fixed font or palette value`)
}
const content = fs.readFileSync(path.join(base, "IslandContent.qml"), "utf8")
assert.doesNotMatch(content, /Accessible\.ignored:\s*!actionEnabled/, "generic disabled actions remain accessible")
assert.match(content, /enabled: actionButton\.actionEnabled\s+Accessible\.role: Accessible\.Button/, "generic actions expose actual disabled state without disabling pointer absorption")
assert.match(content, /Style\.font\.family/)
assert.match(content, /Color\.bar\.text/)
assert.match(content, /Color\.bar\.background/)
assert.match(content, /Color\.muted/)
assert.match(content, /Color\.accent/)
const icon = fs.readFileSync(path.join(base, "ActivityIcon.qml"), "utf8")
assert.match(icon, /import QtQuick\.Shapes/, "shared vector icons use Qt Quick Shapes")
assert.match(content, /id:\s*compactIcon[\s\S]*?width:\s*12[\s\S]*?height:\s*12/, "compact icon has a 12 by 12 unfilled container")
assert.match(content, /ActivityIcon\s*\{[\s\S]*?name: root\.compact\.icon/, "compact content uses the shared semantic icon")
assert.match(icon, /play: "M 3 1 L 12 7 L 3 13 Z"/, "play uses a vector triangle")
assert.match(icon, /pause: "M 3 1 H 5 V 13 H 3 Z M 9 1 H 11 V 13 H 9 Z"/, "pause uses two vector bars")
assert.doesNotMatch(content, /id:\s*iconPlate|compactHasProgress|compactProgressTrack/, "compact mode has no filled badge or progress track")
assert.match(content, /primaryText:\s*Color\.bar\.text/, "all content modes use the bar foreground")
assert.match(content, /surface:\s*Color\.bar\.background/, "secondary controls use the bar background")
assert.doesNotMatch(content, /Color\.popups\.(?:text|background)/, "content never switches to the popup palette")
const visual = fs.readFileSync(path.join(base, "ActivityVisual.qml"), "utf8")
assert.match(visual, /fillColor:\s*Color\.bar\.background/, "the island body always matches the bar")
assert.doesNotMatch(visual, /incomingExpanded|Color\.popups\.background/, "expansion never switches surface palette")
const body = visual.match(/id:\s*capsuleBackground([\s\S]*?)\n  \}/)
assert.ok(body, "the capsule background is independently inspectable")
assert.match(body[1], /^\s*fillColor:\s*Color\.bar\.background\s*$/m, "every activity role uses the bar background directly")
const mediaContent = fs.readFileSync(path.join(base, "MediaContent.qml"), "utf8")
assert.match(mediaContent, /Color\.bar\.text/, "media text and glyphs use the bar foreground")
assert.match(mediaContent, /Color\.bar\.background/, "media artwork fallback uses the bar palette")
assert.match(mediaContent, /Color\.muted/, "media secondary state uses the muted theme token")
assert.match(mediaContent, /Color\.accent/, "media controls and progress use the accent token")
const surface = fs.readFileSync(path.join(base, "IslandSurface.qml"), "utf8")
for (const field of ["fontFamily", "background", "foreground", "accent"]) assert.match(surface, new RegExp(`${field}:`), `diagnostic publishes ${field}`)
console.log("theme contract assertions passed")
